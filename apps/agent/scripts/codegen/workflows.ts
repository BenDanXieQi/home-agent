import { fileURLToPath } from "node:url";
import {
  scanModules,
  validateModuleNames,
  writeGeneratedFile,
} from "./modules";

const workflowDirectory = fileURLToPath(
  new URL("../../src/workflows/", import.meta.url),
);
const outputPath = `${workflowDirectory}registry.generated.ts`;

export async function generateWorkflows() {
  const infrastructureFiles = new Set([
    "index.ts",
    "definition.ts",
    "structured-output.ts",
    "registry.generated.ts",
  ]);
  const files = scanModules(workflowDirectory, "*.ts").filter(
    (file) => !infrastructureFiles.has(file),
  );
  const names = files.map((file) => file.slice(0, -".ts".length));
  validateModuleNames(names);

  const source = `// Generated by scripts/codegen/workflows.ts. Do not edit.
import { z } from "zod";
import type { Config } from "../config";
import type { agentWorkflowInputSchema, spatialPlanningScopeSchema } from "@home-agent/api/agent-workflows";
import { closeWorkflows, type WorkflowContext, type WorkflowInstance, type WorkflowRegistry } from "./definition";
${names.map((name, index) => `import { createWorkflow as createWorkflow${index}, modelConfiguration as modelConfiguration${index} } from "./${name}";`).join("\n")}

export const workflowConfigurationSchema = z.object({
${names.map((_name, index) => `  [modelConfiguration${index}.key]: modelConfiguration${index}.schema,`).join("\n")}
});

export function configureWorkflowRegistry(config: Config) {
${names.map((_name, index) => `  const modelRef${index} = config[modelConfiguration${index}.key] ?? config.AGENT_MODEL;`).join("\n")}
  return {
    modelRefs: [${names.map((_name, index) => `modelRef${index}`).join(", ")}],
    createRegistry(context: Omit<WorkflowContext, "modelRef">) {
  const registry = {
${names.map((name, index) => `    "${name}": createWorkflow${index}({ ...context, modelRef: modelRef${index} }),`).join("\n")}
  } satisfies WorkflowRegistry;
  const instances: WorkflowInstance[] = Object.values(registry);
  return {
    execute: async (input: z.output<typeof agentWorkflowInputSchema>, signal: AbortSignal) => {
      switch (input.workflow) {
${names
  .map(
    (name) => `        case "${name}":
          return { workflow: input.workflow, result: await registry["${name}"].run?.(input.input, signal) };`,
  )
  .join("\n")}
      }
      return input satisfies never;
    },
    retainScope: async (scope: z.output<typeof spatialPlanningScopeSchema> | null) => {
      const results = await Promise.allSettled(instances.map(async (instance) => {
        await instance.retainScope?.(scope);
      }));
      const errors = results.flatMap((result) => result.status === "rejected" ? [result.reason] : []);
      if (errors.length) throw new AggregateError(errors, "Workflow scope cleanup failed");
    },
    close: () => closeWorkflows(instances),
  };
    },
  };
}
`;
  await writeGeneratedFile(outputPath, source);
}

if (import.meta.main) await generateWorkflows();
